def data_goldens():
    """Freeze the whole event-disjoint labeled cohort, without copying waveforms."""
    events, manifest = [], {}
    for split, count in (("train", 30000), ("val", 3000), ("test", 3000)):
        path = DATA / f"{split}.npz"
        with path.open("rb") as f:
            digest = hashlib.file_digest(f, "sha256").hexdigest()
        assert digest == DATA_HASHES[split], f"Prepared dataset {split} hash mismatch"
        with np.load(path, allow_pickle=False) as z:
            x = z["waveforms"]
            labels = np.column_stack([z["p_idx"], z["s_idx"]])
            ids = set(z["source_id"].tolist())
            assert x.shape == (count, 3, 3000) and x.dtype == np.float32
            assert labels.dtype == np.int32 and np.isfinite(x).all()
            assert str(z["component_order"]) == "ZNE" and float(z["sampling_rate"]) == 100
            assert np.all((labels[:, 0] >= 100) & (labels[:, 0] < 3000))
            assert np.array_equal(labels[:, 1] == -1, z["s_outside_window"])
            valid = labels[:, 1] >= 0
            assert np.all(labels[valid, 1] > labels[valid, 0])
            assert np.all(labels[valid, 1] < 3000)
            # Physical sanity: a median onset energy increase, not a model score.
            ratios = []
            for b, pick in enumerate(labels[:, 0]):
                pre = x[b, 0, pick-100:pick].astype(np.float64)
                post = x[b, 0, pick:pick+100].astype(np.float64)
                ratios.append(np.sqrt(np.mean(post**2)/np.mean(pre**2)))
            assert np.median(ratios) > 2
            manifest[split] = {"sha256": digest, "bytes": path.stat().st_size,
                               "records": count, "events": len(ids),
                               "absent_S": int((~valid).sum()),
                               "P_sample_range": [int(labels[:, 0].min()), int(labels[:, 0].max())],
                               "P_median_s": float(np.median(labels[:, 0]))*DT,
                               "S_median_s": float(np.median(labels[valid, 1]))*DT,
                               "median_Z_post_pre_RMS": float(np.median(ratios))}
            np.savez_compressed(OUT / f"stead_{split}_labels.npz", labels=labels,
                                sample_interval_s=np.array(DT, np.float64))
        events.append(ids)
        print(split, json.dumps(manifest[split]), flush=True)
        del x
    assert not (events[0] & events[1] or events[0] & events[2] or events[1] & events[2])
    return manifest


def training_schedule():
    """All augmentation randomness is frozen here, not generated by tests."""
    from reference_train import (
        BATCH,
        FINAL_LEARNING_RATE,
        LEARNING_RATE,
        REFERENCE_SEEDS,
        STEPS,
        schedule_path,
    )
    rates = (FINAL_LEARNING_RATE + .5*(LEARNING_RATE-FINAL_LEARNING_RATE) *
             (1+np.cos(np.pi*np.arange(STEPS, dtype=np.float64)/(STEPS-1)))).astype(np.float32)
    for seed in REFERENCE_SEEDS:
        rng = np.random.default_rng(seed)
        indices = np.empty((STEPS, BATCH), np.int32)
        shifts = np.empty_like(indices)
        polarities = np.empty((STEPS, BATCH), np.float32)
        for i in range(STEPS):
            indices[i] = rng.integers(0, 30000, BATCH)
            shifts[i] = rng.integers(-500, 501, BATCH)
            polarities[i] = rng.choice(np.array([-1, 1], np.float32), size=BATCH)
        np.savez_compressed(schedule_path(seed), batch_indices=indices,
                            shifts=shifts, polarities=polarities, learning_rates=rates,
                            final_rng_state=np.array(json.dumps(rng.bit_generator.state, sort_keys=True)))


def round4_schedule():
    """One frozen schedule shared by three initialization seeds (<20 MB total)."""
    from round4_config import (
        BATCH,
        FINAL_LEARNING_RATE,
        LEARNING_RATE,
        PARAMETERS,
        SCHEDULE,
        SEED,
        STEPS,
        WARMUP_STEPS,
        WIDTHS,
    )
    rng = np.random.default_rng(SEED)
    indices = rng.integers(0, 30000, (STEPS, BATCH), dtype=np.int32)
    shifts = rng.integers(-500, 501, (STEPS, BATCH), dtype=np.int32)
    polarities = rng.choice(np.array([-1, 1], np.float32), (STEPS, BATCH))
    angles = rng.uniform(-np.pi, np.pi, (STEPS, BATCH)).astype(np.float32)
    warmup = LEARNING_RATE * np.arange(1, WARMUP_STEPS+1, dtype=np.float64) / WARMUP_STEPS
    decay = FINAL_LEARNING_RATE + .5 * (LEARNING_RATE-FINAL_LEARNING_RATE) * (
        1 + np.cos(np.pi * np.arange(STEPS-WARMUP_STEPS, dtype=np.float64) / (STEPS-WARMUP_STEPS-1)))
    rates = np.r_[warmup, decay].astype(np.float32)
    # Independent shape/parameter arithmetic; no GPU needed to validate the
    # declared capacity and schedule. Accuracy/runtime still need actual runs.
    conv_pairs = [(3, WIDTHS[0]), *pairwise(WIDTHS),
                  *[(a+b, b) for a, b in zip(WIDTHS[:0:-1], WIDTHS[-2::-1])]]
    count = sum(7*a*b+b for a, b in conv_pairs) + 3*WIDTHS[0] + 3
    assert count == PARAMETERS == 647971
    assert rates[0] == np.float32(1e-6) and rates[-1] == np.float32(FINAL_LEARNING_RATE)
    assert rates[WARMUP_STEPS-1] == rates[WARMUP_STEPS] == np.float32(LEARNING_RATE)
    assert np.all(np.diff(rates[:WARMUP_STEPS]) > 0) and np.all(np.diff(rates[WARMUP_STEPS:]) <= 0)
    np.savez_compressed(SCHEDULE, batch_indices=indices, shifts=shifts,
                        polarities=polarities, rotation_angles=angles, learning_rates=rates)


def loss64(logits, targets):
    shift = logits - logits.max(axis=-1, keepdims=True)
    logp = shift - np.log(np.exp(shift).sum(axis=-1, keepdims=True))
    return -np.sum(targets * logp) / np.prod(logits.shape[:-1])


def loss_fixture():
    rng = np.random.default_rng(SEEDS["loss"])
    # Reference evaluates the exact float32 input values in float64.
    logits = rng.normal(0, 1.5, (2, 7, 3)).astype(np.float32)
    targets = np.eye(3)[rng.integers(0, 3, (2, 7))].astype(np.float32)
    targets[:, ::2, :] = [.25, .5, .25]  # Exactly representable soft labels.
    l64, y64 = logits.astype(np.float64), targets.astype(np.float64)
    shift = l64 - l64.max(axis=-1, keepdims=True)
    prob = np.exp(shift) / np.exp(shift).sum(axis=-1, keepdims=True)
    grad = (prob - y64) / 14
    directions = []
    while len(directions) < 4:
        d = rng.normal(size=logits.shape)
        d /= np.linalg.norm(d)
        d = d.astype(np.float32)
        if abs(np.sum(grad * d)) > 0.03:
            directions.append(d)
    directions = np.array(directions)
    h = T["FD_STEP"]
    plus = (logits + h*directions).astype(np.float32)
    minus = (logits - h*directions).astype(np.float32)
    effective = (plus.astype(np.float64)-minus.astype(np.float64))/(2*h)
    fd = np.array([(loss64(p.astype(np.float64), y64) - loss64(m.astype(np.float64), y64))/(2*h)
                   for p, m in zip(plus, minus)])
    projected = np.sum(grad * effective, axis=(1, 2, 3))
    fd_errors = {"float64": float(np.linalg.norm(fd-projected)/np.linalg.norm(fd))}
    observed32 = np.array([(float(np.float32(loss64(p, targets)))-float(np.float32(loss64(m, targets))))/(2*h)
                           for p, m in zip(plus, minus)])
    fd_errors["numpy_float32"] = float(np.linalg.norm(observed32-projected)/np.linalg.norm(observed32))
    import torch
    ytorch = torch.from_numpy(targets)
    def torch_loss(a):
        return float(-(ytorch * torch.log_softmax(torch.from_numpy(a), dim=-1)).sum()/14)
    observed_torch = np.array([(torch_loss(p)-torch_loss(m))/(2*h) for p, m in zip(plus, minus)])
    fd_errors["torch_float32"] = float(np.linalg.norm(observed_torch-projected)/np.linalg.norm(observed_torch))
    assert max(fd_errors.values()) < T["GRAD_RTOL"] / 2, fd_errors
    print("FD relative errors", fd_errors, flush=True)
    offsets = rng.uniform(-8, 8, (2, 7, 1)).astype(np.float32)
    extreme = np.array([[[100., -100., 0.], [-90., 90., 0.]]], dtype=np.float32)
    extreme_targets = np.array([[[0., 1., 0.], [1., 0., 0.]]], dtype=np.float32)
    return {"logits": logits, "targets": targets, "loss": np.array(loss64(l64, y64)),
            "gradient": grad, "directions": effective, "finite_difference": fd,
            "plus_logits": plus, "minus_logits": minus,
            "fd_validation_errors": np.array(list(fd_errors.values())),
            "offsets": offsets, "extreme_logits": extreme, "extreme_targets": extreme_targets,
            "extreme_loss": np.array(loss64(extreme.astype(float), extreme_targets.astype(float)))}


def scoring_cases():
    # Explicit expected rows: TP,FP,FN,F1,median absolute error (seconds).
    # These numbers are hand-counted, not produced by the tested scorer.
    definitions = [
        ("perfect", [[20, 70], [-1, -1]], [(0, 0, 20), (0, 1, 70)],
         [[1, 0, 0, 1, 0], [1, 0, 0, 1, 0]]),
        ("boundary", [[20, 70]], [(0, 0, 30), (0, 1, 60)],
         [[1, 0, 0, 1, .1], [1, 0, 0, 1, .1]]),
        ("outside", [[20, 70]], [(0, 0, 31), (0, 1, 59)],
         [[0, 1, 1, 0, np.inf], [0, 1, 1, 0, np.inf]]),
        ("duplicates", [[20, 70], [-1, -1]],
         [(0, 0, 20), (0, 0, 40), (1, 0, 10), (0, 1, 70), (1, 1, 60)],
         [[1, 2, 0, .5, 0], [1, 1, 0, 2/3, 0]]),
        ("missed", [[20, 70]], [(0, 1, 70)],
         [[0, 0, 1, 0, np.inf], [1, 0, 0, 1, 0]]),
        ("empty", [[-1, -1]], [],
         [[0, 0, 0, 1, np.inf], [0, 0, 0, 1, np.inf]]),
        ("swapped", [[20, 70]], [(0, 0, 70), (0, 1, 20)],
         [[0, 1, 1, 0, np.inf], [0, 1, 1, 0, np.inf]]),
    ]
    for name, labels, picks, expected in definitions:
        probs = np.zeros((len(labels), 100, 3), dtype=np.float32)
        probs[:, :, 0] = 1
        for b, phase, index in picks:
            probs[b, index, 0] = .25
            probs[b, index, phase + 1] = .75
        np.savez_compressed(OUT / f"score_{name}.npz", probabilities=probs,
                            labels=np.array(labels, dtype=np.int64), expected=np.array(expected))
    # Inclusive threshold, plateaus, disconnected regions, and both record edges.
    p = np.zeros((1, 20, 3), dtype=np.float32)
    p[0, [0, 1, 5, 6, 7, 19], 1] = [.5, .5, .5, .75, .75, .5]
    p[0, 12, 1] = .499
    p[:, :, 0] = 1 - p[:, :, 1]
    np.savez_compressed(OUT / "decoder.npz", probabilities=p, expected=np.array([0, 6, 19]))
    # Required trace normalization: exact power-of-two gains preserve float32
    # input mantissas; zero and constant traces must share the zero-RMS guard.
    constant = np.zeros((2, 3000, 3), dtype=np.float32)
    constant[1, :, :] = [1., 2., -3.]
    np.savez_compressed(OUT / "normalization.npz", constant_waveforms=constant,
                        gains=np.array([.125, 1., 8.], np.float32).reshape(3, 1, 1))


def reference_audits(seed, round4=False):
    """Freeze real decoded picks and deterministic broken-model mutations.

    This scorer is independent of tests/metrics.py and never imports it.
    Arrays contain sample indices, -1 padded. Wrong time scale maps i -> i//2;
    +0.15 s bias adds 15 samples and drops picks beyond the recorded window.
    """
    if round4:
        from round4_config import work_dir
    else:
        from reference_train import work_dir
    work = work_dir(seed)
    if not (work / "completion.json").exists():
        return None
    completion = json.loads((work / "completion.json").read_text())
    assert completion["checkpoint_removed"]
    assert not any((work / name).exists() for name in ("checkpoint.pt", "model.npz", "optimizer.npz"))
    for name, digest in completion["evidence_sha256"].items():
        assert hashlib.sha256((work / name).read_bytes()).hexdigest() == digest
    if round4:
        assert set(completion["source_sha256"]) == {"reference_mlx.py", "round4_config.py"}
        for name, digest in completion["source_sha256"].items():
            assert hashlib.sha256((ROOT / "judge" / name).read_bytes()).hexdigest() == digest
    else:
        assert hashlib.sha256((ROOT / "judge" / "reference_train.py").read_bytes()).hexdigest() == completion["reference_source_sha256"]
    picks = json.loads((work / "test_picks.json").read_text())["picks"]
    untrained = json.loads((work / "untrained_picks.json").read_text())
    assert untrained["seed"] == seed and untrained["step"] == 0
    variants = [picks, untrained["picks"],
                [[row[1], row[0]] for row in picks],
                [[[i//2 for i in phase] for phase in row] for row in picks],
                [[[i+15 for i in phase if i+15 < 3000] for phase in row] for row in picks]]
    names = ["reference", "untrained", "swapped", "half_time_scale", "bias_0.15s"]
    padded = np.full((5, len(picks), 2, max(len(p) for v in variants for row in v for p in row)), -1, np.int32)
    with np.load(OUT / "stead_test_labels.npz", allow_pickle=False) as z:
        labels = z["labels"]
    results = []
    for variant_index, predictions in enumerate(variants):
        rows = []
        for phase in range(2):
            tp = fp = fn = 0
            residuals = []
            for b, row in enumerate(predictions):
                p = np.array(row[phase], np.int64)
                padded[variant_index, b, phase, :len(p)] = p
                truth = int(labels[b, phase])
                distances = np.abs(p-truth)
                matched = truth >= 0 and len(p) > 0 and distances.min() <= T["MATCH_TOLERANCE_S"] / DT
                tp += int(matched)
                fp += len(p)-int(matched)
                fn += int(truth >= 0)-int(matched)
                if matched:
                    residuals.append(float(distances.min())*DT)
            denominator = 2*tp+fp+fn
            rows.append([tp, fp, fn, 2*tp/denominator if denominator else 1.,
                         float(np.median(residuals)) if residuals else np.inf])
        results.append(rows)
    results = np.array(results, np.float64)
    original = json.loads((work / "test_metrics.json").read_text())
    assert np.array_equal(results[0, :, :3], original["counts_P_S"])
    assert np.array_equal(results[0, :, 3], original["f1_P_S"])
    prefix = "round4_reference_audit" if round4 else "reference_audit"
    np.savez_compressed(OUT / f"{prefix}_{seed}.npz", picks=padded,
                        expected_scores=results, variants=np.array(names))
    return {name: {"f1_P_S": result[:, 3].tolist(),
                   "f1_micro": float(2*result[:, 0].sum()/(2*result[:, 0]+result[:, 1]+result[:, 2]).sum())}
            for name, result in zip(names, results)}


